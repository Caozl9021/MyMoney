/// 按 App `Tokens.kt` 的 `swatchFor` 算法稳定映射分类颜色。
pub fn swatch_for(name: &str, fallback_index: usize) -> &'static str {
    if name.is_empty() {
        return AB_ACCENT_SWATCHES[fallback_index % AB_ACCENT_SWATCHES.len()];
    }
    for (color, words) in SWATCH_RULES {
        if words.iter().any(|w| name.contains(w)) {
            return color;
        }
    }
    let custom_len = 9i32;
    let mut h: i32 = 0;
    for unit in name.encode_utf16() {
        h = h.wrapping_mul(31).wrapping_add(unit as i32);
    }
    let idx = h.rem_euclid(custom_len) as usize;
    AB_ACCENT_SWATCHES[idx]
}
